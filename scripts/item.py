#!/usr/bin/env python3
"""item.py — addressable access to one checklist item (or a search), without loading a 200 KB chapter.

  python3 scripts/item.py D10-004              full item as markdown (metadata + Test/How/Proof/…)
  python3 scripts/item.py D10-004 D10-006      several items
  python3 scripts/item.py D10-004 --json       the parsed item as JSON
  python3 scripts/item.py --domain D10         every item id + title in a domain (same as the card table)
  python3 scripts/item.py --grep "javascriptinterface"   search titles + bodies, print matching ids
  python3 scripts/item.py --field how D10-004  only one field (test|how|proof|escalation|ruled_out_when|skip_when|record)
  python3 scripts/item.py --xrefs D10-004      items this one references, and items that reference it

Reads json/Dnn.json (generated by scripts/build-checklist.py). Run the build first if json/ is missing.
"""
import json, os, re, sys, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = os.path.join(ROOT, "json")
E = {"critical": "🟥", "high": "🟧", "medium": "🟨", "low": "🟩", "support": "⬜"}


def load_domain(d):
    p = os.path.join(J, d + ".json")
    if not os.path.exists(p):
        sys.exit(f"!! {p} missing — run: python3 scripts/build-checklist.py")
    return json.load(open(p, encoding="utf-8"))


def load_all():
    return [json.load(open(p, encoding="utf-8")) for p in sorted(glob.glob(os.path.join(J, "D*.json")))]


def find(iid):
    d = iid[:3]
    for i in load_domain(d)["items"]:
        if i["id"] == iid:
            return i
    sys.exit(f"!! no item {iid}")


def render(i):
    L = []
    A = L.append
    A(f"### {i['id']} · {i['title']}")
    A("")
    A("| | |"); A("|---|---|")
    A(f"| **Severity ceiling** | {E[i['severity']]} {i['severity']} ({i['vrt_priority']}) |")
    for k, lab in [("vrt", "VRT"), ("attacker", "Attacker"), ("applies_to", "Applies to"),
                   ("prerequisites", "Prerequisites"), ("depends_on", "Depends on"), ("evidence", "Evidence"),
                   ("cost", "Cost"), ("maps_to", "Maps to")]:
        if i.get(k):
            A(f"| **{lab}** | {i[k]} |")
    A("")
    for k, lab in [("skip_when", "Skip when"), ("test", "Test"), ("how", "How"), ("proof", "Proof"),
                   ("escalation", "Escalation"), ("ruled_out_when", "Ruled out when"), ("record", "Record")]:
        if i.get(k):
            A(f"- **{lab}:** " + i[k].replace("\n", "\n  "))
    if i.get("xrefs"):
        A(""); A("Cross-references: " + ", ".join(f"`{x}`" for x in i["xrefs"]))
    return "\n".join(L)


def main():
    a = sys.argv[1:]
    if not a:
        print(__doc__); sys.exit(1)
    if a[0] == "--domain":
        d = load_domain(a[1].upper())
        print(f"# {d['id']} · {d['name']} — {len(d['items'])} items")
        for i in d["items"]:
            print(f"{i['id']}  {E[i['severity']]} {i['vrt_priority']:<6} {'/'.join(i['attacker_ids']) or 'n/a':<12} {i['title']}")
        return
    if a[0] == "--grep":
        pat = re.compile(a[1], re.I)
        for d in load_all():
            for i in d["items"]:
                hay = " ".join([i["title"], i.get("test", ""), i.get("how", ""), i.get("proof", ""),
                                i.get("applies_to", ""), i.get("maps_to", "")])
                if pat.search(hay):
                    print(f"{i['id']}  {E[i['severity']]} {i['title']}")
        return
    if a[0] == "--xrefs":
        iid = a[1].upper(); me = find(iid)
        print("references:", ", ".join(me["xrefs"]) or "none")
        back = [i["id"] for d in load_all() for i in d["items"] if iid in i.get("xrefs", [])]
        print("referenced by:", ", ".join(back) or "none")
        return
    field = None
    if a[0] == "--field":
        field = a[1]; a = a[2:]
    as_json = "--json" in a
    ids = [x.upper() for x in a if re.fullmatch(r'D\d\d-\d{3}', x, re.I)]
    if not ids:
        print(__doc__); sys.exit(1)
    for iid in ids:
        i = find(iid)
        if as_json:
            print(json.dumps({k: v for k, v in i.items() if k != "body_md"}, ensure_ascii=False, indent=1))
        elif field:
            print(i.get(field, ""))
        else:
            print(render(i)); print()


if __name__ == "__main__":
    main()
