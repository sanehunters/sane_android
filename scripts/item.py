#!/usr/bin/env python3
"""item.py — addressable access to one checklist item (or a search), without loading a 200 KB chapter.

  python3 scripts/item.py D10-004              full item as markdown (metadata + Skip when/Test/How/Proof/…)
  python3 scripts/item.py D10-004 D10-006      several items
  python3 scripts/item.py D10-004 --brief      Test + How + Proof + Ruled out when (the cheapest way to run an item)
  python3 scripts/item.py D10-004 --json       the parsed item as JSON
  python3 scripts/item.py --domain D10         every item id + title in a domain (same as the card table)
  python3 scripts/item.py --grep "javascriptinterface"   search titles, every field and the metadata cells
  python3 scripts/item.py D10-004 --field how  only one field (test|how|proof|escalation|ruled_out_when|skip_when|
                                               record|requires|vrt|attacker|applies_to|maps_to|severity_note|…)
  python3 scripts/item.py D10-004 --xrefs      items this one references, and items that reference it

Options may come before or after the ids. Reads json/Dnn.json (generated by scripts/build-checklist.py); run the
build first if json/ is missing. Schema: docs/11-item-schema.md.
"""
import argparse, json, os, re, sys, glob

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
J = os.path.join(ROOT, "json")
E = {"critical": "🟥", "high": "🟧", "medium": "🟨", "low": "🟩", "support": "⬜", "varies": "🔷", "?": "❔"}
META_ROWS = [("vrt", "VRT"), ("attacker", "Attacker"), ("applies_to", "Applies to"), ("requires", "Requires"),
             ("maps_to", "Maps to"), ("record", "Record")]
BODY_ROWS = [("skip_when", "Skip when"), ("test", "Test"), ("how", "How"), ("proof", "Proof"),
             ("escalation", "Escalation"), ("ruled_out_when", "Ruled out when")]
BRIEF_ROWS = [("skip_when", "Skip when"), ("test", "Test"), ("how", "How"), ("proof", "Proof"), ("ruled_out_when", "Ruled out when")]
FIELDS = ["title", "severity", "severity_floor", "severity_note", "vrt", "vrt_priority", "vrt_best", "attacker", "attacker_ids",
          "applies_to", "requires", "requires_tags", "maps_to", "record", "skip_when", "test", "how", "proof", "escalation",
          "ruled_out_when", "xrefs", "domain_refs", "ids", "legacy_meta"]


def sev(i):
    return E.get(i.get("severity"), "?")


def load_index():
    p = os.path.join(J, "index.json")
    if not os.path.exists(p):
        sys.exit(f"!! {p} missing — run: python3 scripts/build-checklist.py")
    return json.load(open(p, encoding="utf-8"))


def load_domain(d):
    index = load_index()
    if d not in index["domains"]:
        sys.exit(f"!! no chapter for {d}: nothing to build from (a declared-but-unwritten domain, see ISSUES.md, or not a domain). "
                 f"Chapters: {' '.join(sorted(index['domains']))}")
    p = os.path.join(J, d + ".json")
    if not os.path.exists(p):
        sys.exit(f"!! {p} missing — run: python3 scripts/build-checklist.py")
    return json.load(open(p, encoding="utf-8"))


def load_all():
    return [json.load(open(p, encoding="utf-8")) for p in sorted(glob.glob(os.path.join(J, "D*.json")))]


def find(iid):
    d = iid[:3]
    for i in load_domain(d)["items"]:
        if i["id"] == iid:
            return i
    sys.exit(f"!! no item {iid}")


def field_line(lab, text):
    """Render '- **Label:** text' with continuation lines indented. A field whose text STARTS with a code fence
    must put the fence on its own line, otherwise the fence is glued to the label and the code block never opens
    for the reader (the chapters write the fence on the line after the label; the parser strips that newline)."""
    body = text.replace("\n", "\n  ")
    if text.lstrip().startswith("```"):
        return f"- **{lab}:**\n  " + body
    return f"- **{lab}:** " + body


def sev_tag(i):
    floor = "" if i["severity_floor"] == i["severity"] else f" / {i['severity_floor']} alone"
    best = "" if i.get("vrt_best", i["vrt_priority"]) == i["vrt_priority"] else f" ↑{i['vrt_best']}"
    return f"{i['severity']}{floor} · VRT {i['vrt_priority']}{best} · {'/'.join(i['attacker_ids']) or 'n/a'}"


def render(i, brief=False):
    L = []; A = L.append
    if brief:
        A(f"### {i['id']} · {i['title']}  [{sev_tag(i)}]")
        if i.get("requires"): A(f"Requires: {i['requires']}")
        for k, lab in BRIEF_ROWS:
            if i.get(k): A(field_line(lab, i[k]))
        return "\n".join(L)
    A(f"### {i['id']} · {i['title']}")
    A("")
    A("| | |"); A("|---|---|")
    parsed = f"{sev(i)} {i['severity']}" + ("" if i["severity_floor"] == i["severity"] else f" ({i['severity_floor']} standalone)")
    best = "" if i.get("vrt_best", i["vrt_priority"]) == i["vrt_priority"] else f" (best {i['vrt_best']})"
    A(f"| **Severity ceiling** | {i['severity_note']} — parsed: {parsed} · VRT {i['vrt_priority']}{best} |")
    for k, lab in META_ROWS:
        if i.get(k):
            A(f"| **{lab}** | {i[k]} |")
    for lab, v in (i.get("legacy_meta") or {}).items():
        A(f"| **{lab}** (deprecated row, docs/11 §7) | {v} |")
    A("")
    for k, lab in BODY_ROWS:
        if i.get(k):
            A(field_line(lab, i[k]))
    if i.get("xrefs"):
        A(""); A("Cross-references: " + ", ".join(f"`{x}`" for x in i["xrefs"]))
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("ids", nargs="*", help="item ids (Dnn-NNN)")
    ap.add_argument("--brief", action="store_true", help="Test + How + Proof + Ruled out when only")
    ap.add_argument("--json", action="store_true", help="the parsed item as JSON")
    ap.add_argument("--field", metavar="NAME", help="print one field only")
    ap.add_argument("--domain", metavar="Dnn", help="list every item of a domain")
    ap.add_argument("--grep", metavar="REGEX", help="search titles, fields and metadata (case-insensitive)")
    ap.add_argument("--xrefs", action="store_true", help="items this one references, and items that reference it")
    a = ap.parse_args()
    ids = []
    for x in a.ids:
        if not re.fullmatch(r'D\d\d-\d{3}', x, re.I):
            sys.exit(f"!! not an item id: {x} (expected Dnn-NNN)")
        ids.append(x.upper())
    if a.domain:
        d = load_domain(a.domain.upper())
        print(f"# {d['id']} · {d['name']} — {len(d['items'])} items")
        for i in d["items"]:
            print(f"{i['id']}  {sev(i)} {i['vrt_priority']:<6} {'/'.join(i['attacker_ids']) or 'n/a':<12} {i['title']}")
        return
    if a.grep:
        pat = re.compile(a.grep, re.I)
        keys = [k for k, _ in BODY_ROWS] + ["vrt", "attacker", "severity_note", "applies_to", "maps_to", "requires", "record"]
        for d in load_all():
            for i in d["items"]:
                hay = " ".join([i["title"]] + [i.get(k) or "" for k in keys])
                if pat.search(hay):
                    print(f"{i['id']}  {sev(i)} {i['title']}")
        return
    if not ids:
        ap.print_help(); sys.exit(1)
    if a.xrefs:
        everything = load_all()
        for iid in ids:
            me = find(iid)
            print(f"{iid} references:", ", ".join(me["xrefs"]) or "none")
            back = [i["id"] for d in everything for i in d["items"] if iid in i.get("xrefs", [])]
            print(f"{iid} referenced by:", ", ".join(back) or "none")
        return
    if a.field and a.field not in FIELDS:
        sys.exit(f"!! unknown field {a.field}; one of: {' '.join(FIELDS)}")
    for iid in ids:
        i = find(iid)
        if a.json:
            print(json.dumps(i, ensure_ascii=False, indent=1))
        elif a.field:
            v = i.get(a.field, "")
            print(", ".join(v) if isinstance(v, list) else (json.dumps(v, ensure_ascii=False) if isinstance(v, dict) else v))
        else:
            print(render(i, a.brief)); print()


if __name__ == "__main__":
    main()
