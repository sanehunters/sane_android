#!/usr/bin/env bash
# SessionStart: print the resume card so a fresh (or compacted) session knows where it is without being told.
set -uo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"
HOOK_INPUT="$(cat 2>/dev/null || true)"
cd "$REPO" || exit 0
echo "### sane_android — session context (auto-generated by .claude/hooks/session-start.sh)"
echo "Entry point: START.md (read it in full once). Rules: R0 breadth before depth · R7 state on disk, committed in the engagement's own evidence repo and pushed to its PRIVATE remote (never to the methodology origin)."
E="$(active_engagement)"
if [ -n "$E" ]; then
  echo "Active engagement: $E  (override with SANE_ENGAGEMENT=<path>)"
  if is_evidence_repo "$E"; then r="$(evidence_remote "$E")"; echo "Evidence remote: ${r:-none — $NO_REMOTE_MSG}"; else echo "Evidence: this folder is not its own git repository — migrate it (BugBountyTarget/README.md) before committing anything."; fi
  python3 scripts/state.py "$E" 2>/dev/null || echo "(state.py failed — read $E/report/assessment-status.md)"
  [ -f "$E/report/assessment-status.md" ] && echo "Resume rule: read $E/report/assessment-status.md; never re-walk RULED OUT; continue from NEXT TARGET."
else
  echo "No engagement folder exists yet. For a new target: START.md §3 (bash scripts/doctor.sh → scripts/new-engagement.sh <Target> [--remote <private git url>])."
fi
out="$(bash scripts/doctor.sh --brief 2>/dev/null || true)"
[ -n "$out" ] || out="doctor.sh produced no output (bash <4? run: bash scripts/doctor.sh) — environment UNVERIFIED"
echo "Environment: $out"
exit 0
