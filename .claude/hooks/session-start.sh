#!/usr/bin/env bash
# SessionStart: print the resume card so a fresh (or compacted) session knows where it is without being told.
set -uo pipefail
. "$(dirname "${BASH_SOURCE[0]}")/_lib.sh"
HOOK_INPUT="$(cat 2>/dev/null || true)"
cd "$REPO" || exit 0
echo "### sane_android — session context (auto-generated by .claude/hooks/session-start.sh)"
echo "Entry point: START.md (read it in full once). Rules: R0 breadth before depth · R7 state on disk, pushed."
E="$(active_engagement)"
if [ -n "$E" ]; then
  echo "Active engagement: $E  (override with SANE_ENGAGEMENT=<path>)"
  python3 scripts/state.py "$E" 2>/dev/null || echo "(state.py failed — read $E/report/assessment-status.md)"
  [ -f "$E/report/assessment-status.md" ] && echo "Resume rule: read $E/report/assessment-status.md; never re-walk RULED OUT; continue from NEXT TARGET."
else
  echo "No engagement folder exists yet. For a new target: START.md §3 (scripts/doctor.sh → scripts/new-engagement.sh <Target>)."
fi
echo "Environment: $(bash scripts/doctor.sh --brief 2>/dev/null || echo 'doctor.sh unavailable')"
exit 0
